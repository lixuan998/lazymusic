// Package nvimconfig installs the user's lazy.nvim spec for the bundled plugin.
package nvimconfig

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type Result struct {
	Path, Backup string
	Changed      bool
}

// Write is idempotent and backs up differing existing content before replacing
// it atomically. Runtime paths exclude DESTDIR, which is only a packaging root.
func Write(configDir, pluginDir, binary string) (Result, error) {
	var err error
	for _, path := range []*string{&configDir, &pluginDir, &binary} {
		if *path == "" {
			return Result{}, fmt.Errorf("Neovim config, plugin and binary paths are required")
		}
		*path, err = filepath.Abs(*path)
		if err != nil {
			return Result{}, err
		}
	}
	dir := filepath.Join(configDir, "lua", "plugins")
	if err := os.MkdirAll(dir, 0755); err != nil {
		return Result{}, err
	}
	path := filepath.Join(dir, "lazymusic.lua")
	result := Result{Path: path}
	if info, err := os.Lstat(path); err == nil && info.Mode()&os.ModeSymlink != 0 {
		path, err = filepath.EvalSymlinks(path)
		if err != nil {
			return result, fmt.Errorf("resolve Neovim config symlink: %w", err)
		}
	} else if err != nil && !os.IsNotExist(err) {
		return result, err
	}
	content := []byte(fmt.Sprintf(`-- Generated by lazymusic. make install updates this file.
return {
  {
    name = "lazymusic",
    dir = %s,
    main = "lazymusic",
    cmd = { "LazyMusic", "LazyMusicHide" },
    keys = {
      { "<leader>mm", function() require("lazymusic").open() end, desc = "Open lazymusic" },
    },
    opts = { cmd = %s },
  },
}
`, luaString(pluginDir), luaString(binary)))
	old, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return result, err
	}
	if err == nil && bytes.Equal(old, content) {
		return result, nil
	}
	if err == nil {
		backup, err := os.CreateTemp(filepath.Dir(path), "lazymusic.lua.bak-*")
		if err != nil {
			return result, err
		}
		result.Backup = backup.Name()
		_, writeErr := backup.Write(old)
		if writeErr == nil {
			writeErr = backup.Sync()
		}
		closeErr := backup.Close()
		if writeErr != nil {
			return result, writeErr
		}
		if closeErr != nil {
			return result, closeErr
		}
	}
	err = writeAtomic(path, content, 0600)
	result.Changed = err == nil
	return result, err
}

// WriteHelpTags makes :help usable for a locally installed plugin, including
// machines where Neovim itself is not available during make install.
func WriteHelpTags(dir string) error {
	content, err := os.ReadFile(filepath.Join(dir, "lazymusic.txt"))
	if err != nil {
		return err
	}
	tags := map[string]bool{}
	for _, match := range regexp.MustCompile(`\*([A-Za-z0-9_.:-]+)\*`).FindAllSubmatch(content, -1) {
		tags[string(match[1])] = true
	}
	var names []string
	for name := range tags {
		names = append(names, name)
	}
	sort.Strings(names)
	var index strings.Builder
	for _, name := range names {
		fmt.Fprintf(&index, "%s\tlazymusic.txt\t/*%s*\n", name, name)
	}
	return writeAtomic(filepath.Join(dir, "tags"), []byte(index.String()), 0644)
}

func writeAtomic(path string, content []byte, mode os.FileMode) error {
	file, err := os.CreateTemp(filepath.Dir(path), ".lazymusic-config-*")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	err = file.Chmod(mode)
	if err == nil {
		_, err = file.Write(content)
	}
	if err == nil {
		err = file.Sync()
	}
	closeErr := file.Close()
	if err == nil {
		err = closeErr
	}
	if err == nil {
		err = os.Rename(file.Name(), path)
	}
	return err
}

// Lua quoted strings use decimal byte escapes for control characters; Go's
// Unicode escapes are not valid Lua 5.1 syntax. Preserve UTF-8 path bytes.
func luaString(value string) string {
	var out strings.Builder
	out.WriteByte('"')
	for _, b := range []byte(value) {
		switch b {
		case '\\', '"':
			out.WriteByte('\\')
			out.WriteByte(b)
		default:
			if b < 32 || b == 127 {
				fmt.Fprintf(&out, "\\%03d", b)
			} else {
				out.WriteByte(b)
			}
		}
	}
	out.WriteByte('"')
	return out.String()
}
